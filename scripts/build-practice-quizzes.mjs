#!/usr/bin/env node
/**
 * Public practice quizzes (PHASE-EX10 deliverable 2).
 *
 *   node scripts/build-practice-quizzes.mjs [--check]
 *
 * Reads the PRIVATE knowledge-test bank (digital-creativity-pedagogy/excellence/
 * assessment/, never published) and writes public pages for units with
 * `public_quiz: true` questions. Each question sits in an element with
 * `data-question`; the answer is revealed on click (<details>, no JavaScript).
 *
 * --check: exit 1 if a committed page differs from what this script would write.
 * Wired into `npm run prebuild`.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

import { escapeHtml } from './lib/deck-render.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BANK = join(root, 'digital-creativity-pedagogy/excellence/assessment/question-bank.yml');
export const PER_UNIT = 5;
const LETTERS = 'ABCDEFGH';

/** "Surname, Given. 2012. …" → "Surname 2012" (Chicago author-date short). */
export function authorDate(chicago) {
  const text = String(chicago || '').replace(/\s+/g, ' ').trim();
  const m = text.match(/^(.*?)(?:, eds?)?\. ((?:1[89]|20)\d\d)\./);
  if (!m) return null;
  const parts = m[1].split(/,? and |, /);
  const surnames = [parts[0]];
  for (const p of parts.slice(2)) surnames.push(p.trim().split(' ').pop());
  let names;
  if (surnames.length > 3) names = `${surnames[0]} et al.`;
  else if (surnames.length === 3) names = `${surnames[0]}, ${surnames[1]}, and ${surnames[2]}`;
  else if (surnames.length === 2) names = `${surnames[0]} and ${surnames[1]}`;
  else names = surnames[0];
  return `${names} ${m[2]}`;
}

/**
 * Options for an mcq: answer + distractors. The answer's position rotates with `slot`.
 */
export function options(q, slot = 0) {
  const wrong = (q.distractors || []).map(String);
  const offset = parseInt(createHash('sha256').update(String(q.unit)).digest('hex').slice(0, 8), 16);
  const at = (slot + offset) % (wrong.length + 1);
  const all = [...wrong];
  all.splice(at, 0, String(q.answer));
  return { all, correct: at };
}

function lessonTitle(lessonPath) {
  const rel = lessonPath.replace(/^\//, '').replace(/\/$/, '');
  const mdPath = join(root, 'docs', rel, 'index.md');
  if (!existsSync(mdPath)) return rel.split('/').pop();
  const md = readFileSync(mdPath, 'utf8');
  return (md.match(/^title:\s*['"]?(.*?)['"]?\s*$/m) || [])[1] || rel.split('/').pop();
}

export function questionHtml(q, n, { lesson, references, slot = 0, locale = 'en' }) {
  const es = locale === 'es';
  const cite = references[q.ref] ? authorDate(references[q.ref].chicago) : null;
  const opts = q.type === 'mcq' ? options(q, slot) : null;
  const body = opts
    ? `<ol class="practice-quiz__options" type="A">${opts.all.map((o) => `<li>${escapeHtml(o)}</li>`).join('')}</ol>`
    : `<p class="practice-quiz__hint">${es
      ? (q.type === 'case' ? 'Aplica la lección a esta situación en dos o tres frases y después compara.' : 'Responde en una o dos frases y después compara.')
      : (q.type === 'case' ? 'Apply the lesson to this situation in two or three sentences, then compare.' : 'Answer in one or two sentences, then compare.')}</p>`;
  const answer = opts ? `(${LETTERS[opts.correct]}) ${escapeHtml(q.answer)}` : escapeHtml(q.answer);
  return [
    `<article class="practice-quiz__question" id="q${n}" data-question="${escapeHtml(q.id)}">`,
    `<p class="practice-quiz__stem"><strong>${n}.</strong> ${escapeHtml(q.stem)}</p>`,
    body,
    '<details>',
    `<summary>${es ? 'Mostrar respuesta' : 'Show answer'}</summary>`,
    `<p><strong>${es ? 'Respuesta:' : 'Answer:'}</strong> ${answer}</p>`,
    `<p class="practice-quiz__check">${es ? 'Compruébalo en la lección:' : 'Check it in the lesson:'} <a href="{{ '${lesson}' | relative_url }}#${escapeHtml(q.anchor)}">${escapeHtml(q.where)}</a>${cite ? ` · <a href="#ref-${escapeHtml(q.ref)}">(${escapeHtml(cite)})</a>` : ''}</p>`,
    '</details>',
    '</article>',
  ].join('\n');
}

export function quizPage(unit, info, questions, { references, title, locale = 'en' }) {
  const es = locale === 'es';
  const refs = [...new Set(questions.map((q) => q.ref))].sort();
  const fm = [
    '---',
    'layout: default',
    `title: "${es ? `Práctica · ${unit}` : `${unit} practice quiz`}"`,
    `lang: ${locale}`,
    `permalink: /practice/${locale}/${info.slug}/`,
    `description: "${es ? `Cinco preguntas de práctica sobre ${unit}; las respuestas se abren al pulsar. Sin calificación ni registro.` : `Five practice questions on ${unit} with answers you open on click. Practice only: not graded, nothing recorded.`}"`,
    `references: [${refs.join(', ')}]`,
    '---',
    '',
  ].join('\n');
  return `${fm}{% comment %}Generated by scripts/build-practice-quizzes.mjs (npm run prebuild). Do not edit by hand.{% endcomment %}
<div class="practice-quiz practice-quiz--page prose prose-slate dark:prose-invert max-w-none">
<h1>${es ? `Cuestionario de práctica · ${escapeHtml(unit)}` : `${escapeHtml(unit)} practice quiz`}</h1>
<p>${es ? 'Cinco preguntas sobre' : 'Five questions on'} <a href="{{ '${info.lesson}' | relative_url }}">${escapeHtml(title)}</a>. ${es ? 'Responde primero de memoria; después abre cada respuesta y comprueba la lección. El esfuerzo de recordar antes de mirar forma parte del ejercicio.' : 'Answer each one from memory first, then open the answer and check the lesson. Trying to recall before you look is the point of the exercise.'}</p>
<p>${es ? 'Esta página es solo de práctica: no se califica, no es el examen y no se registra ninguna respuesta.' : 'This page is practice only: it is not graded, it is not the exam, and nothing you do here is recorded.'}</p>
${questions.map((q, i) => questionHtml(q, i + 1, { lesson: info.lesson, references, locale, slot: questions.slice(0, i).filter((x) => x.type === 'mcq').length })).join('\n')}
<section class="practice-quiz__references" id="references">
<h2>${es ? 'Referencias' : 'References'}</h2>
{% include references.html %}
</section>
<p>${es ? 'Más práctica:' : 'More practice:'} <a href="{{ '/practice/${locale}/' | relative_url }}">${es ? 'todos los cuestionarios' : 'all practice quizzes'}</a>${es ? '.' : '. Transposition brief (D2 ≡ ACT3): see Evaluation — one cartel from another language.'}</p>
</div>
`;
}

